// veduta schema-gen: assets/schemas/*.schema.json から Go のバリデータ関数を生成する。
//
// JSON Schema が単一の真実の源であり、生成物 generated_validators.go はコミットされる。
// CI で `go generate ./...` 再実行後に差分が無いことを検証する。
// 対応するのは veduta のスキーマが使う JSON Schema のサブセットのみ:
//
//	type(object/array/string/number/integer/boolean), properties, required,
//	additionalProperties:false, enum(文字列), pattern, minLength/maxLength(コードポイント),
//	minimum/maximum, minItems/maxItems, items, $defs / ローカル $ref
//
// 生成コードは失敗時に JSON Pointer 形式のパスを含む診断を返す。
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strconv"
	"strings"
)

type node = map[string]any

type generator struct {
	buf      strings.Builder
	defs     map[string]any
	patterns map[string]string // pattern → var name (決定論的に採番)
	varSeq   int
}

func main() {
	log.SetFlags(0)
	log.SetPrefix("schema-gen: ")

	src := "../../assets/schemas/architecture.schema.json"
	data, err := os.ReadFile(src)
	if err != nil {
		log.Fatalf("スキーマを読めません: %v", err)
	}
	var root node
	if err := json.Unmarshal(data, &root); err != nil {
		log.Fatalf("スキーマの JSON が不正です: %v", err)
	}

	g := &generator{patterns: map[string]string{}}
	if d, ok := root["$defs"].(map[string]any); ok {
		g.defs = d
	} else {
		g.defs = map[string]any{}
	}

	// 先に全パターンを収集して決定論的に採番する。
	g.collectPatterns(root)
	for _, name := range sortedKeys(g.defs) {
		g.collectPatterns(g.defs[name].(map[string]any))
	}

	var body strings.Builder
	g.buf = strings.Builder{}
	g.emitFuncHeader("vArchitectureRoot", "IR 文書のルート")
	g.emitNode(root, "p", "v", 1)
	g.emitLine(0, "}")
	body.WriteString(g.buf.String())
	body.WriteString("\n")

	for _, name := range sortedKeys(g.defs) {
		g.buf = strings.Builder{}
		g.emitFuncHeader(defFuncName(name), "$defs/"+name)
		g.emitNode(g.defs[name].(map[string]any), "p", "v", 1)
		g.emitLine(0, "}")
		body.WriteString(g.buf.String())
		body.WriteString("\n")
	}

	var out strings.Builder
	out.WriteString("// Code generated by veduta schema-gen from assets/schemas/architecture.schema.json. DO NOT EDIT.\n\n")
	out.WriteString("package schema\n\n")
	out.WriteString("import (\n")
	out.WriteString("\t\"math\"\n")
	out.WriteString("\t\"regexp\"\n")
	out.WriteString("\t\"strconv\"\n")
	out.WriteString("\t\"unicode/utf8\"\n\n")
	out.WriteString("\t\"github.com/ZONO33LHD/archy-go/internal/diag\"\n")
	out.WriteString(")\n\n")

	if len(g.patterns) > 0 {
		out.WriteString("var (\n")
		type pv struct{ name, pat string }
		var pats []pv
		for pat, name := range g.patterns {
			pats = append(pats, pv{name, pat})
		}
		sort.Slice(pats, func(i, j int) bool { return pats[i].name < pats[j].name })
		for _, p := range pats {
			fmt.Fprintf(&out, "\t%s = regexp.MustCompile(%s)\n", p.name, strconv.Quote(p.pat))
		}
		out.WriteString(")\n\n")
	}

	out.WriteString("// ValidateArchitecture は architecture IR の汎用デコード結果 (any) をスキーマ検証する。\n")
	out.WriteString("func ValidateArchitecture(v any) diag.List {\n")
	out.WriteString("\tvar ds diag.List\n")
	out.WriteString("\tvArchitectureRoot(\"\", v, &ds)\n")
	out.WriteString("\treturn ds\n")
	out.WriteString("}\n\n")
	out.WriteString(body.String())

	// 未使用 import の防止: strconv / utf8 / math は生成内容によっては未使用になり得る。
	code := out.String()
	code = stripUnusedImport(code, "strconv", "strconv.")
	code = stripUnusedImport(code, "unicode/utf8", "utf8.")
	code = stripUnusedImport(code, "math", "math.")
	code = stripUnusedImport(code, "regexp", "regexp.")

	formatted, err := format.Source([]byte(code))
	if err != nil {
		log.Fatalf("生成コードの整形に失敗しました: %v", err)
	}
	if err := os.WriteFile("generated_validators.go", formatted, 0o644); err != nil {
		log.Fatalf("生成物を書けません: %v", err)
	}
	log.Printf("generated_validators.go を生成しました")
}

func stripUnusedImport(code, path, marker string) string {
	if strings.Contains(strings.SplitN(code, ")\n", 2)[1], marker) {
		return code
	}
	return strings.Replace(code, "\t\""+path+"\"\n", "", 1)
}

func sortedKeys(m map[string]any) []string {
	ks := make([]string, 0, len(m))
	for k := range m {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	return ks
}

func defFuncName(def string) string {
	return "vDef" + strings.ToUpper(def[:1]) + def[1:]
}

func (g *generator) emitFuncHeader(name, doc string) {
	fmt.Fprintf(&g.buf, "// %s は %s を検証する。\n", name, doc)
	fmt.Fprintf(&g.buf, "func %s(p string, v any, ds *diag.List) {\n", name)
}

func (g *generator) emitLine(indent int, format string, args ...any) {
	g.buf.WriteString(strings.Repeat("\t", indent))
	fmt.Fprintf(&g.buf, format, args...)
	g.buf.WriteString("\n")
}

func (g *generator) collectPatterns(s node) {
	if pat, ok := s["pattern"].(string); ok {
		if _, exists := g.patterns[pat]; !exists {
			g.patterns[pat] = "rePat" + strconv.Itoa(len(g.patterns))
		}
	}
	for _, key := range []string{"items"} {
		if sub, ok := s[key].(map[string]any); ok {
			g.collectPatterns(sub)
		}
	}
	if props, ok := s["properties"].(map[string]any); ok {
		for _, name := range sortedKeys(props) {
			g.collectPatterns(props[name].(map[string]any))
		}
	}
}

func (g *generator) fresh(prefix string) string {
	g.varSeq++
	return prefix + strconv.Itoa(g.varSeq)
}

// emitNode は schema ノード s に対する検証コードを出力する。
// pathExpr は JSON Pointer を表す Go 式、valExpr は検証対象値の Go 式。
func (g *generator) emitNode(s node, pathExpr, valExpr string, ind int) {
	if ref, ok := s["$ref"].(string); ok {
		def := strings.TrimPrefix(ref, "#/$defs/")
		if def == ref {
			log.Fatalf("ローカル $defs 以外の $ref は未対応です: %s", ref)
		}
		if _, ok := g.defs[def]; !ok {
			log.Fatalf("$ref 先が存在しません: %s", ref)
		}
		g.emitLine(ind, "%s(%s, %s, ds)", defFuncName(def), pathExpr, valExpr)
		return
	}
	typ, _ := s["type"].(string)
	switch typ {
	case "object":
		g.emitObject(s, pathExpr, valExpr, ind)
	case "string":
		g.emitString(s, pathExpr, valExpr, ind)
	case "number", "integer":
		g.emitNumber(s, typ == "integer", pathExpr, valExpr, ind)
	case "boolean":
		v := g.fresh("b")
		g.emitLine(ind, "if _, ok := %s.(bool); !ok {", valExpr)
		g.emitLine(ind+1, `addSchemaDiag(ds, "schema/type", %s, "真偽値が必要です", "値を true または false にする")`, pathExpr)
		g.emitLine(ind, "}")
		_ = v
	case "array":
		g.emitArray(s, pathExpr, valExpr, ind)
	default:
		log.Fatalf("未対応の schema type: %q", typ)
	}
}

func (g *generator) emitObject(s node, pathExpr, valExpr string, ind int) {
	obj := g.fresh("obj")
	g.emitLine(ind, "%s, ok := %s.(map[string]any)", obj, valExpr)
	g.emitLine(ind, "if !ok {")
	g.emitLine(ind+1, `addSchemaDiag(ds, "schema/type", %s, "オブジェクトが必要です", "値を { } 形式のオブジェクトにする")`, pathExpr)
	g.emitLine(ind+1, "return")
	g.emitLine(ind, "}")

	props, _ := s["properties"].(map[string]any)
	propNames := sortedKeys(props)

	// additionalProperties:false — 未知フィールドの拒否。
	if ap, ok := s["additionalProperties"].(bool); ok && !ap {
		k := g.fresh("k")
		g.emitLine(ind, "for _, %s := range sortedKeys(%s) {", k, obj)
		g.emitLine(ind+1, "switch %s {", k)
		if len(propNames) > 0 {
			quoted := make([]string, len(propNames))
			for i, n := range propNames {
				quoted[i] = strconv.Quote(n)
			}
			g.emitLine(ind+1, "case %s:", strings.Join(quoted, ", "))
		}
		g.emitLine(ind+1, "default:")
		g.emitLine(ind+2, `addSchemaDiag(ds, "schema/unknown-field", %s+"/"+ptrEscape(%s), "未知のフィールドです", "フィールドを削除する", "スキーマで定義された名前に修正する")`, pathExpr, k)
		g.emitLine(ind+1, "}")
		g.emitLine(ind, "}")
	}

	// required — スキーマの配列順で検査する。
	if req, ok := s["required"].([]any); ok {
		for _, r := range req {
			name := r.(string)
			g.emitLine(ind, "if _, ok := %s[%q]; !ok {", obj, name)
			g.emitLine(ind+1, `addSchemaDiag(ds, "schema/required", %s, "必須フィールド '%s' がありません", "'%s' フィールドを追加する")`, pathExpr, name, name)
			g.emitLine(ind, "}")
		}
	}

	for _, name := range propNames {
		sub := props[name].(map[string]any)
		val := g.fresh("pv")
		g.emitLine(ind, "if %s, ok := %s[%q]; ok {", val, obj, name)
		g.emitNode(sub, fmt.Sprintf("%s+%q", pathExpr, "/"+ptrEscapeStatic(name)), val, ind+1)
		g.emitLine(ind, "}")
	}
}

func (g *generator) emitString(s node, pathExpr, valExpr string, ind int) {
	sv := g.fresh("s")
	g.emitLine(ind, "%s, ok := %s.(string)", sv, valExpr)
	g.emitLine(ind, "if !ok {")
	g.emitLine(ind+1, `addSchemaDiag(ds, "schema/type", %s, "文字列が必要です", "値を \"...\" 形式の文字列にする")`, pathExpr)
	g.emitLine(ind, "} else {")
	inner := ind + 1
	used := false
	if enum, ok := s["enum"].([]any); ok {
		used = true
		vals := make([]string, len(enum))
		disp := make([]string, len(enum))
		for i, e := range enum {
			vals[i] = strconv.Quote(e.(string))
			disp[i] = e.(string)
		}
		g.emitLine(inner, "switch %s {", sv)
		g.emitLine(inner, "case %s:", strings.Join(vals, ", "))
		g.emitLine(inner, "default:")
		g.emitLine(inner+1, `addSchemaDiag(ds, "schema/enum", %s, "許可されない値です (許可: %s)", "値を次のいずれかに変更する: %s")`,
			pathExpr, strings.Join(disp, " | "), strings.Join(disp, " | "))
		g.emitLine(inner, "}")
	}
	if pat, ok := s["pattern"].(string); ok {
		used = true
		g.emitLine(inner, "if !%s.MatchString(%s) {", g.patterns[pat], sv)
		g.emitLine(inner+1, `addSchemaDiag(ds, "schema/pattern", %s, "形式が不正です (許可パターン: %s)", "英数字で始まり、英数字・'_'・'-' のみ 64 文字以内の値に変更する")`,
			pathExpr, strings.ReplaceAll(pat, `\`, `\\`))
		g.emitLine(inner, "}")
	}
	minL, hasMin := numVal(s["minLength"])
	maxL, hasMax := numVal(s["maxLength"])
	if hasMin || hasMax {
		used = true
		n := g.fresh("n")
		g.emitLine(inner, "%s := utf8.RuneCountInString(%s)", n, sv)
		if hasMin {
			g.emitLine(inner, "if %s < %d {", n, int(minL))
			g.emitLine(inner+1, `addSchemaDiag(ds, "schema/length", %s, "文字数が不足しています (最小 %d コードポイント、実際 "+strconv.Itoa(%s)+")", "%d 文字以上の値にする")`,
				pathExpr, int(minL), n, int(minL))
			g.emitLine(inner, "}")
		}
		if hasMax {
			g.emitLine(inner, "if %s > %d {", n, int(maxL))
			g.emitLine(inner+1, `addSchemaDiag(ds, "schema/length", %s, "文字数が上限を超えています (最大 %d コードポイント、実際 "+strconv.Itoa(%s)+")", "意味を保ったまま %d 文字以内に短縮する")`,
				pathExpr, int(maxL), n, int(maxL))
			g.emitLine(inner, "}")
		}
	}
	if !used {
		g.emitLine(inner, "_ = %s", sv)
	}
	g.emitLine(ind, "}")
}

func (g *generator) emitNumber(s node, integer bool, pathExpr, valExpr string, ind int) {
	nv := g.fresh("f")
	g.emitLine(ind, "%s, ok := %s.(float64)", nv, valExpr)
	g.emitLine(ind, "if !ok {")
	g.emitLine(ind+1, `addSchemaDiag(ds, "schema/type", %s, "数値が必要です", "値を数値リテラルにする")`, pathExpr)
	g.emitLine(ind, "} else {")
	inner := ind + 1
	if integer {
		g.emitLine(inner, "if %s != math.Trunc(%s) {", nv, nv)
		g.emitLine(inner+1, `addSchemaDiag(ds, "schema/type", %s, "整数が必要です", "小数部を持たない整数値にする")`, pathExpr)
		g.emitLine(inner, "}")
	}
	if min, ok := numVal(s["minimum"]); ok {
		g.emitLine(inner, "if %s < %s {", nv, formatGoFloat(min))
		g.emitLine(inner+1, `addSchemaDiag(ds, "schema/range", %s, "数値が下限 %s を下回っています", "値を %s 以上にする")`,
			pathExpr, formatDispFloat(min), formatDispFloat(min))
		g.emitLine(inner, "}")
	}
	if max, ok := numVal(s["maximum"]); ok {
		g.emitLine(inner, "if %s > %s {", nv, formatGoFloat(max))
		g.emitLine(inner+1, `addSchemaDiag(ds, "schema/range", %s, "数値が上限 %s を超えています", "値を %s 以下にする")`,
			pathExpr, formatDispFloat(max), formatDispFloat(max))
		g.emitLine(inner, "}")
	}
	g.emitLine(ind, "}")
}

func (g *generator) emitArray(s node, pathExpr, valExpr string, ind int) {
	av := g.fresh("a")
	g.emitLine(ind, "%s, ok := %s.([]any)", av, valExpr)
	g.emitLine(ind, "if !ok {")
	g.emitLine(ind+1, `addSchemaDiag(ds, "schema/type", %s, "配列が必要です", "値を [ ] 形式の配列にする")`, pathExpr)
	g.emitLine(ind, "} else {")
	inner := ind + 1
	if min, ok := numVal(s["minItems"]); ok {
		g.emitLine(inner, "if len(%s) < %d {", av, int(min))
		g.emitLine(inner+1, `addSchemaDiag(ds, "schema/items", %s, "要素数が不足しています (最小 %d、実際 "+strconv.Itoa(len(%s))+")", "要素を %d 個以上にする")`,
			pathExpr, int(min), av, int(min))
		g.emitLine(inner, "}")
	}
	// 要素検証ループの上限。maxItems 超過は既に拒否確定なので、超過分は検証しない。
	// これにより巨大配列 (例: components:[0,0,...]) が診断・CPU を爆発させない (§10.9)。
	limit := av
	maxV, hasMax := numVal(s["maxItems"])
	if hasMax {
		g.emitLine(inner, "if len(%s) > %d {", av, int(maxV))
		g.emitLine(inner+1, `addSchemaDiag(ds, "schema/items", %s, "要素数が上限を超えています (最大 %d、実際 "+strconv.Itoa(len(%s))+")", "要素を %d 個以内に減らす")`,
			pathExpr, int(maxV), av, int(maxV))
		g.emitLine(inner, "}")
	}
	if items, ok := s["items"].(map[string]any); ok {
		iv := g.fresh("i")
		ev := g.fresh("e")
		lv := g.fresh("lim")
		g.emitLine(inner, "%s := len(%s)", lv, limit)
		if hasMax {
			g.emitLine(inner, "if %s > %d {", lv, int(maxV))
			g.emitLine(inner+1, "%s = %d", lv, int(maxV))
			g.emitLine(inner, "}")
		}
		g.emitLine(inner, "for %s := 0; %s < %s; %s++ {", iv, iv, lv, iv)
		g.emitLine(inner+1, "if ds.AtCap() {")
		g.emitLine(inner+2, "break")
		g.emitLine(inner+1, "}")
		g.emitLine(inner+1, "%s := %s[%s]", ev, av, iv)
		g.emitNode(items, fmt.Sprintf(`%s+"/"+strconv.Itoa(%s)`, pathExpr, iv), ev, inner+1)
		g.emitLine(inner, "}")
	}
	g.emitLine(ind, "}")
}

func numVal(v any) (float64, bool) {
	f, ok := v.(float64)
	return f, ok
}

// formatGoFloat は Go ソースに埋め込む数値リテラル。
func formatGoFloat(f float64) string {
	return strconv.FormatFloat(f, 'g', -1, 64)
}

// formatDispFloat は診断メッセージに埋め込む表示用数値。
func formatDispFloat(f float64) string {
	return strconv.FormatFloat(f, 'f', -1, 64)
}

// ptrEscapeStatic は生成時に確定するプロパティ名の JSON Pointer エスケープ。
func ptrEscapeStatic(s string) string {
	s = strings.ReplaceAll(s, "~", "~0")
	return strings.ReplaceAll(s, "/", "~1")
}
